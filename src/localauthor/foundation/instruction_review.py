"""Narrow, explicit code-request checks. Not a semantic judge or code execution."""
import re


def code_blocks(content):
    opening=re.compile(r'^ {0,3}(`{3,}|~{3,})[^\r\n]*(?:\r?\n|$)',re.M)
    blocks=[];position=0
    while match:=opening.search(content,position):
        closing=re.compile(r'^ {0,3}'+re.escape(match[1][0])+'{'+str(len(match[1]))+r',}[ \t]*(?:\r?\n|$)',re.M)
        end=closing.search(content,match.end())
        blocks.append(content[match.end():end.start() if end else len(content)])
        if not end:break
        position=end.end()
    return blocks


def review_code_request(prompt,content):
    blocks=code_blocks(content)
    if not blocks:return {'checked':[],'violations':[]}
    code='\n'.join(blocks);checked=[];violations=[]
    def check(name,passed,feedback):
        checked.append(name)
        if not passed:violations.append(feedback)
    limits={int(n) for n in re.findall(r'\b(?:at[eé]|no m[aá]ximo|at most)\s+(\d{1,3})\s+(?:linhas|lines)\b',prompt,re.I)}
    if len(limits)==1 and 0<next(iter(limits))<=999:
        limit=next(iter(limits));actual=sum(len(block.splitlines()) for block in blocks)
        check('code_line_limit',actual<=limit,f'O código tem {actual} linhas; o limite explícito é {limit}. Conte também linhas em branco e preserve todas as funcionalidades pedidas.')
    # These clauses are recognized only in the current user's request, never
    # inferred from source documents, earlier replies or a project's examples.
    bans=' '.join(re.findall(r'\bsem\s+([^.!?\n]+)',prompt,re.I))
    if re.search(r'\buseEffect\b',bans,re.I):
        check('no_useEffect',not re.search(r'\buseEffect\b',code),'O pedido proíbe useEffect; retire esse uso.')
    if re.search(r'\bimports?\s+locais\b',bans,re.I):
        check('no_relative_imports',not re.search(r'(?:from\s*|import\s*)[\'"]\.',code),'O pedido proíbe imports locais; declare os tipos e funções necessários no arquivo solicitado.')
    if re.search(r'\btailwind\b',bans,re.I):
        # CSS values such as textDecoration: "line-through" are not classes.
        classes=[]
        for attribute in re.finditer(r'\bclass(?:Name)?\s*=\s*(?:([\'"])(.*?)\1|\{(.*?)\})',code,re.S):
            if attribute[1]:classes.append(attribute[2])
            else:classes.extend(match[2] for match in re.finditer(r'([\'"`])(.*?)\1',attribute[3],re.S))
        utility=re.search(r'\b(?:p[xytrbl]?-\d|m[xytrbl]?-\d|bg-[a-z]|text-(?:lg|sm|xl|gray|white)|font-bold|space-y-\d|rounded|line-through)\b',' '.join(classes))
        check('no_tailwind_utilities',not utility,'O pedido proíbe Tailwind; retire as classes utilitárias. Use HTML sem essas classes ou CSS nativo quando permitido.')
    if re.search(r'PostgreSQL',prompt,re.I) and re.search(r'gerad[oa]\s+como\s+identidade|\bAS\s+IDENTITY\b',prompt,re.I):
        check('postgres_identity',bool(re.search(r'GENERATED\s+(?:ALWAYS|BY\s+DEFAULT)\s+AS\s+IDENTITY',code,re.I)) and not re.search(r'\bSERIAL\b',code,re.I),
            'Foi pedida coluna identity do PostgreSQL; use GENERATED ALWAYS AS IDENTITY ou GENERATED BY DEFAULT AS IDENTITY, não SERIAL.')
    return {'checked':checked,'violations':violations}
